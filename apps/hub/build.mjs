// Builds the self-contained Hub: one ESM file with every TestLens package and the embedded
// landing page + Postman snippet inside, zero runtime dependencies. Output: dist/testlens-hub.mjs
import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');

// 1. embed static assets as a generated module (works both under tsx in the repo and in the bundle)
const landing = await fs.readFile(path.join(here, 'public', 'index.html'), 'utf8');
const snippet = await fs.readFile(path.join(root, 'integrations', 'postman', 'testlens-postman-snippet.js'), 'utf8');
const pkg = JSON.parse(await fs.readFile(path.join(here, 'package.json'), 'utf8'));
await fs.writeFile(
  path.join(here, 'src', 'embedded.ts'),
  `// GENERATED by build.mjs — do not edit. Landing page and Postman snippet embedded for the single-file Hub.\nexport const HUB_VERSION = ${JSON.stringify(pkg.version)};\nexport const LANDING_HTML = ${JSON.stringify(landing)};\nexport const SNIPPET_JS = ${JSON.stringify(snippet)};\n`,
);

// 2. bundle
await fs.mkdir(path.join(here, 'dist'), { recursive: true });
const result = await build({
  entryPoints: [path.join(here, 'src', 'server.ts')],
  outfile: path.join(here, 'dist', 'testlens-hub.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'esm',
  banner: { js: '#!/usr/bin/env node' },
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  metafile: true,
});
const out = path.join(here, 'dist', 'testlens-hub.mjs');
const size = (await fs.stat(out)).size;
console.log(`built ${path.relative(root, out)} (${Math.round(size / 1024)} KB, ${Object.keys(result.metafile.inputs).length} modules bundled)`);
